from app import tutor_coach
from app.tutor_coach import CoachContext, coach, next_stage


def context(source_ids=None):
    return CoachContext(
        question_id="q-1",
        question_text="Bir olayın nedenini soran tarih sorusu.",
        choice_text="Bir yorum ifadesi",
        section_title="Tarihin Doğası",
        source_ids=source_ids if source_ids is not None else ["meb-1"],
        evidence="Tarih, geçmişteki insan faaliyetlerini yer ve zaman göstererek inceler.",
        error_type="neden_sonuc",
    )


def test_stage_machine_only_reveals_after_submission():
    assert next_stage(None, False) == "soru_analizi"
    assert next_stage("soru_analizi", False) == "hatirlayani_ortaya_cikar"
    assert next_stage("hatirlayani_ortaya_cikar", False) == "kanitla_bag_kur"
    assert next_stage("kanitla_bag_kur", False) == "sik_elemesi"
    assert next_stage("sik_elemesi", False) == "ogrenci_yaniti"
    assert next_stage("sik_elemesi", True) == "gerekceli_aciklama"


def test_answer_key_never_reaches_prompt_or_early_reply(monkeypatch):
    monkeypatch.setenv("LOCAL_TUTOR_LLM_SERVE", "1")
    captured = []

    def fake_hint(stage, supplied_context, message):
        prompt = tutor_coach._prompt(stage, supplied_context, message)
        captured.append(prompt)
        return "A şıkkı doğrudur.", {"llm": 1, "first_token": 1}

    monkeypatch.setattr(tutor_coach, "_llm_hint", fake_hint)
    reply = coach(context(), None, "yardım et", False, "A", "C")
    assert reply.stage == "soru_analizi"
    assert not reply.can_reveal_explanation
    assert "C" not in captured[0]
    # Unsafe model text is discarded in favour of the deterministic hint.
    assert "A şıkkı" not in reply.student_prompt


def test_no_approved_source_abstains():
    reply = coach(context([]), None, "yardım et", False, None, "B")
    assert reply.abstain_reason == "approved_source_unavailable"
    assert reply.source_ids == []
    assert not reply.can_reveal_explanation

def test_early_model_fact_is_rejected_even_without_option_label(monkeypatch):
    monkeypatch.setenv("LOCAL_TUTOR_LLM_SERVE", "1")

    def fake_hint(*_args):
        return "Bu olay MÖ VI. yüzyılda gerçekleşmiştir.", {"llm": 1, "first_token": 1}

    monkeypatch.setattr(tutor_coach, "_llm_hint", fake_hint)
    reply = coach(context(), None, "yardım et", False, "A", "C")
    assert reply.student_prompt != "Bu olay MÖ VI. yüzyılda gerçekleşmiştir."
    assert reply.student_prompt.endswith("?")


def test_final_explanation_is_server_only_and_can_name_verified_choice(monkeypatch):
    def model_must_not_run(*_args):
        raise AssertionError("Final explanation must not be generated by the local model")

    monkeypatch.setattr(tutor_coach, "_llm_hint", model_must_not_run)
    reply = coach(context(), "ogrenci_yaniti", "B seçtim", True, "B", "C", "Kaynağa uygun ifade")
    assert reply.stage == "gerekceli_aciklama"
    assert reply.can_reveal_explanation
    assert "Kaynağa uygun ifade" in reply.student_prompt


def test_same_choice_twice_gets_source_correction_before_reveal():
    repeated = CoachContext(**{**context().__dict__, "repeat_attempts": 2})
    reply = coach(repeated, "kanitla_bag_kur", "eminim", False, "A", "C")
    assert reply.stage == "sik_elemesi"
    assert "Kaynaktaki" in reply.student_prompt
    assert "C şıkkı" not in reply.student_prompt


def test_coach_uses_approved_relation_as_a_recall_prompt():
    value = context()
    value = value.__class__(**{**value.__dict__, "evidence_by_role": {"relation": "Olay ile tarih arasındaki bağ kaynakta açıkça belirtilmektedir."}})
    reply = coach(value, "soru_analizi", "Bir tarih hatırlıyorum.", False, None, None, None)
    assert reply.stage == "hatirlayani_ortaya_cikar"
    assert "Olay ile tarih" in reply.student_prompt
